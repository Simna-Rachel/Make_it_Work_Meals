import { GenerationFilters, Recipe } from "@/types/recipe";

export interface GenerateRecipesResponse {
  recipes: Recipe[];
  isMock?: boolean;
  error?: string;
}

const CREATIVE_THEMES = [
  "Aromatic Herbaceous & Citrus Bright",
  "Smoky Caramelized & Deep Umami",
  "Street-Food Inspired & Crispy Textures",
  "Rustic European Hearth Comfort",
  "Zesty Coastal & Vibrant Freshness",
  "Warming Spiced & Silky Comfort",
  "Modern Minimalist Pan-Crafted",
  "Savory Bistro One-Pan Wonders",
];

const DISH_ARCHETYPES = [
  {
    type: "High-Heat Sizzle",
    technique: "pan-searing, stir-frying, crisping, or sautéing in a wide skillet with browned edges",
  },
  {
    type: "Deep Simmer or Broth",
    technique: "aromatic reduction, velvety soup, brothy bowl, gentle braise, or creamy curry",
  },
  {
    type: "Inventive Structured or Baked",
    technique: "crispy savory hash/pancake, roasted medley, stuffed preparation, or dynamic layered bowl",
  },
];

export async function fetchRecipesFromGemini(
  filters: GenerationFilters,
  explicitApiKey?: string
): Promise<GenerateRecipesResponse> {
  // Purely server-side secret API key
  const apiKey = explicitApiKey?.trim() || process.env.GEMINI_API_KEY || "";

  if (!apiKey) {
    throw new Error(
      "GEMINI_API_KEY_MISSING: The server environment variable GEMINI_API_KEY is not configured. Please add GEMINI_API_KEY to your .env.local file."
    );
  }

  const prompt = buildGeminiPrompt(filters);

  // Candidate models with gemini-3.8-flash as primary working model
  const candidateModels = [
    "gemini-3.8-flash",
    "gemini-3.8-flash-lite",
    "gemini-flash-latest",
    "gemini-3-flash-preview",
    "gemini-2.5-flash",
  ];

  const requestBody = {
    contents: [
      {
        parts: [
          {
            text: prompt,
          },
        ],
      },
    ],
    generationConfig: {
      temperature: 0.92, // Increased temperature for high variety & creativity
      topP: 0.95,
      responseMimeType: "application/json",
    },
  };

  let response: Response | null = null;
  let lastErrorMessage = "";

  for (const model of candidateModels) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
      const res = await fetch(url, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(requestBody),
      });

      if (res.ok) {
        response = res;
        break;
      } else {
        const errJson = await res.json().catch(() => ({}));
        lastErrorMessage =
          errJson?.error?.message || `Model ${model} returned status ${res.status}`;

        // If error is model deprecation, not found, or temporary high demand / 503, try next candidate model
        const isTemporaryOrUnavailable =
          res.status === 404 ||
          res.status === 400 ||
          res.status === 503 ||
          res.status === 429 ||
          lastErrorMessage.toLowerCase().includes("not available") ||
          lastErrorMessage.toLowerCase().includes("deprecated") ||
          lastErrorMessage.toLowerCase().includes("high demand") ||
          lastErrorMessage.toLowerCase().includes("overloaded");

        if (isTemporaryOrUnavailable) {
          continue;
        } else {
          throw new Error(lastErrorMessage);
        }
      }
    } catch (e: any) {
      if (e.message && !e.message.includes("not available") && !e.message.includes("deprecated")) {
        throw e;
      }
    }
  }

  if (!response || !response.ok) {
    throw new Error(lastErrorMessage || "Failed to generate recipes with Gemini.");
  }

  const data = await response.json();
  const parts = data?.candidates?.[0]?.content?.parts || [];
  // Robustly extract all text parts (accounting for thought signatures / thinking chunks in Gemini 3.8)
  const rawText = parts.map((p: any) => p.text || "").join("").trim();

  if (!rawText) {
    throw new Error("No recipe response generated by Gemini. Please try again.");
  }

  const recipes = parseGeminiRecipeJson(rawText, filters);
  return { recipes };
}

function buildGeminiPrompt(filters: GenerationFilters): string {
  const { ingredients, dietary, cuisine, maxCookingTime, servings, strictMode, specialNotes } = filters;

  // Pick random creative inspiration seeds for non-deterministic variety
  const randomSeed = Math.random().toString(36).substring(2, 8);
  const theme1 = CREATIVE_THEMES[Math.floor(Math.random() * CREATIVE_THEMES.length)];
  const theme2 = CREATIVE_THEMES[(Math.floor(Math.random() * CREATIVE_THEMES.length) + 3) % CREATIVE_THEMES.length];
  const targetServings = servings && servings > 0 ? servings : 1;

  const timeConstraint = maxCookingTime
    ? `Strict limit: total cooking & prep time must NOT exceed ${maxCookingTime} minutes.`
    : "No strict time limit provided: craft practical, weeknight-friendly meals taking between 15 and 45 minutes.";

  const cuisineDirective =
    cuisine && cuisine !== "Any"
      ? `The user requested ${cuisine} cuisine. To ensure high variety, explore 3 distinctly different regional or stylistic interpretations of ${cuisine} (e.g. one rustic homestyle, one vibrant street-style, one refined pan dish).`
      : `No specific cuisine was requested. You MUST provide 3 COMPLETELY DIFFERENT world cuisines / flavor traditions across the 3 dishes (for example: Recipe 1: Mediterranean / Italian, Recipe 2: East or Southeast Asian, Recipe 3: Latin American, Middle Eastern, or Modern Bistro). Do NOT use the same cuisine twice!`;

  const dietaryDirective =
    dietary && dietary.length > 0 && !dietary.includes("None")
      ? `STRICT DIETARY RESTRICTIONS: Must comply 100% with: ${dietary.join(", ")}.`
      : "Dietary restrictions: None specified.";

  const specialNotesDirective =
    specialNotes && specialNotes.trim()
      ? `- USER'S SPECIAL INSTRUCTIONS & NOTES (CRITICAL TO FOLLOW): "${specialNotes.trim()}". Tailor all 3 recipes to respect and incorporate these specific notes (e.g. spice level, ingredient quantity restrictions, kid-friendly adjustments, cooking methods, etc.)!`
      : "";

  return `You are an elite, Michelin-trained executive chef known for spontaneous culinary creativity and zero food waste.
Your mission is to invent exactly 3 COMPLETELY DIFFERENT, fresh, and exciting recipe suggestions using the user's available ingredients.

[INSPIRATION SESSION ID: ${randomSeed}]
Theme inspirations to weave into today's options: "${theme1}" & "${theme2}".

USER INVENTORY & CONSTRAINTS:
- Available Ingredients: ${ingredients.length > 0 ? ingredients.join(", ") : "Any everyday pantry and fridge ingredients"}
- ${dietaryDirective}
- ${cuisineDirective}
- Cooking Time: ${timeConstraint}
- Target Servings: ${targetServings} person(s)
${specialNotesDirective ? `${specialNotesDirective}\n` : ""}- Ingredient Strictness: ${
    strictMode
      ? "STRICT MODE: Exclusively use the listed ingredients (+ water). Do NOT assume any unlisted pantry staples, butter, oils, or spices unless listed. missingIngredients MUST be empty []."
      : "FLEXIBLE MODE: Center the recipe on the listed ingredients, but you are free to suggest 1 to 2 basic household staples (e.g. olive oil, sea salt, black pepper, garlic, or a squeeze of lemon) if it elevates the dish. Any extra items used MUST be explicitly listed in missingIngredients."
  }

MANDATORY VARIETY RULES:
Every time recipes are generated, they must feel fresh, exciting, and varied.
1. DIVERSE COOKING TECHNIQUES:
   - Recipe 1 must use: ${DISH_ARCHETYPES[0].technique} (Dish Type: ${DISH_ARCHETYPES[0].type})
   - Recipe 2 must use: ${DISH_ARCHETYPES[1].technique} (Dish Type: ${DISH_ARCHETYPES[1].type})
   - Recipe 3 must use: ${DISH_ARCHETYPES[2].technique} (Dish Type: ${DISH_ARCHETYPES[2].type})
2. DIVERSE FLAVOR PROFILES:
   - Contrast acidity, richness, umami, crunch, and aroma across the 3 recipes. Never give two soups or two scrambles.
3. CULINARY SENSIBILITY:
   - Recipes must be logically delicious, foolproof for a home cook, and realistic with the supplied ingredients.

OUTPUT SPECIFICATION:
Return a valid JSON array of exactly 3 recipes matching this structure:
[
  {
    "title": "Creative Appetizing Dish Name",
    "description": "2-3 mouthwatering sentences describing the taste, textures, and technique.",
    "ingredients": [
      "Exact quantity and prep state (e.g., '2 ripe tomatoes, roughly chopped')",
      "Exact quantity and prep state (e.g., '1 tbsp extra virgin olive oil')"
    ],
    "instructions": [
      "Numbered step description with exact timing, heat levels, and visual cues.",
      "Next step description."
    ],
    "prepTime": 10,
    "cookTime": 15,
    "totalTime": 25,
    "difficulty": "Easy",
    "approximateCalories": 360,
    "approximateProtein": "16g",
    "missingIngredients": []
  }
]

Difficulty must be one of: "Easy", "Medium", "Hard".
Return ONLY the raw JSON array. No markdown code blocks, backticks, or conversational text.`;
}

function parseGeminiRecipeJson(rawText: string, filters: GenerationFilters): Recipe[] {
  let cleaned = rawText.trim();
  if (cleaned.startsWith("```json")) {
    cleaned = cleaned.replace(/^```json/, "").replace(/```$/, "").trim();
  } else if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```/, "").replace(/```$/, "").trim();
  }

  const parsed = JSON.parse(cleaned);
  let arrayData: any[] = [];

  if (Array.isArray(parsed)) {
    arrayData = parsed;
  } else if (parsed.recipes && Array.isArray(parsed.recipes)) {
    arrayData = parsed.recipes;
  } else {
    throw new Error("Invalid response format received from Gemini.");
  }

  const targetServings = filters.servings && filters.servings > 0 ? filters.servings : 2;

  return arrayData.slice(0, 3).map((item, index) => {
    const prep = Number(item.prepTime) || 10;
    const cook = Number(item.cookTime) || 15;
    const total = Number(item.totalTime) || prep + cook;
    const titleSlug = (item.title || `meal-${index + 1}`)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 25);
    const uniqueId = `rec_${titleSlug}_${Date.now()}_${index}_${Math.random().toString(36).substring(2, 7)}`;

    return {
      id: uniqueId,
      title: item.title || `Delicious Meal #${index + 1}`,
      description: item.description || "A comforting meal made with your ingredients.",
      ingredients: Array.isArray(item.ingredients) ? item.ingredients : [],
      instructions: Array.isArray(item.instructions) ? item.instructions : [],
      prepTime: prep,
      cookTime: cook,
      totalTime: total,
      difficulty: ["Easy", "Medium", "Hard"].includes(item.difficulty) ? item.difficulty : "Easy",
      approximateCalories: Number(item.approximateCalories) || 350,
      approximateProtein: String(item.approximateProtein || "15g"),
      servings: targetServings,
      dietaryTags: filters.dietary ? filters.dietary.filter((d) => d !== "None") : [],
      cuisine: item.cuisine || (filters.cuisine && filters.cuisine !== "Any" ? filters.cuisine : "Chef's Special"),
      missingIngredients: Array.isArray(item.missingIngredients) ? item.missingIngredients : [],
    };
  });
}

import { MealPlanFilters, WeeklyMealPlan, MealPlanDay } from "@/types/mealPlan";

export interface GenerateMealPlanResponse {
  mealPlan: WeeklyMealPlan;
  isMock?: boolean;
  error?: string;
}

export async function fetchMealPlanFromGemini(
  filters: MealPlanFilters,
  explicitApiKey?: string
): Promise<GenerateMealPlanResponse> {
  const apiKey = explicitApiKey?.trim() || process.env.GEMINI_API_KEY || "";

  if (!apiKey) {
    throw new Error(
      "GEMINI_API_KEY_MISSING: The server environment variable GEMINI_API_KEY is not configured. Please set GEMINI_API_KEY in .env.local."
    );
  }

  const prompt = buildMealPlanPrompt(filters);

  const candidateModels = [
    "gemini-3.8-flash",
    "gemini-3.8-flash-lite",
    "gemini-flash-latest",
    "gemini-3-flash-preview",
    "gemini-2.5-flash",
  ];

  const requestBody = {
    contents: [
      {
        parts: [
          {
            text: prompt,
          },
        ],
      },
    ],
    generationConfig: {
      temperature: 0.9,
      topP: 0.95,
      responseMimeType: "application/json",
    },
  };

  let response: Response | null = null;
  let lastErrorMessage = "";

  for (const model of candidateModels) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
      const res = await fetch(url, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(requestBody),
      });

      if (res.ok) {
        response = res;
        break;
      } else {
        const errJson = await res.json().catch(() => ({}));
        lastErrorMessage =
          errJson?.error?.message || `Model ${model} returned status ${res.status}`;

        const isTemporaryOrUnavailable =
          res.status === 404 ||
          res.status === 400 ||
          res.status === 503 ||
          res.status === 429 ||
          lastErrorMessage.toLowerCase().includes("not available") ||
          lastErrorMessage.toLowerCase().includes("deprecated") ||
          lastErrorMessage.toLowerCase().includes("high demand") ||
          lastErrorMessage.toLowerCase().includes("overloaded");

        if (isTemporaryOrUnavailable) {
          continue;
        } else {
          throw new Error(lastErrorMessage);
        }
      }
    } catch (e: any) {
      if (e.message && !e.message.includes("not available") && !e.message.includes("deprecated")) {
        throw e;
      }
    }
  }

  if (!response || !response.ok) {
    throw new Error(lastErrorMessage || "Failed to generate weekly meal plan with Gemini.");
  }

  const data = await response.json();
  const parts = data?.candidates?.[0]?.content?.parts || [];
  const rawText = parts.map((p: any) => p.text || "").join("").trim();

  if (!rawText) {
    throw new Error("No meal plan response generated by Gemini. Please try again.");
  }

  const mealPlan = parseGeminiMealPlanJson(rawText, filters);
  return { mealPlan };
}

function buildMealPlanPrompt(filters: MealPlanFilters): string {
  const {
    ingredients,
    dietary,
    cuisine,
    durationDays,
    mealScope,
    servings,
    strictMode,
    specialNotes,
  } = filters;

  const dietaryDirective =
    dietary && dietary.length > 0 && !dietary.includes("None")
      ? `STRICT DIETARY RESTRICTIONS: Must comply 100% with: ${dietary.join(", ")}.`
      : "Dietary restrictions: None.";

  const cuisineDirective =
    cuisine && cuisine !== "Any"
      ? `Theme cuisine: Focus predominantly on ${cuisine} inspired cooking with creative variety.`
      : "No single cuisine: provide a delightful mix of comfortable global culinary styles throughout the week.";

  const specialNotesDirective =
    specialNotes && specialNotes.trim()
      ? `- USER'S SPECIAL INSTRUCTIONS: "${specialNotes.trim()}". Follow these instructions carefully across the plan!`
      : "";

  return `You are an expert culinary meal planner and chef.
Design a highly practical, flavorful, zero-food-waste Weekly Meal Plan for ${durationDays} days.

USER PANTRY & SETTINGS:
- Available Ingredients: ${ingredients.length > 0 ? ingredients.join(", ") : "Standard pantry ingredients"}
- ${dietaryDirective}
- ${cuisineDirective}
- Target Servings: ${servings} person(s)
${specialNotesDirective ? `${specialNotesDirective}\n` : ""}- Ingredient Strictness: ${
    strictMode
      ? "STRICT MODE: Try to rely strictly on the listed ingredients. Minimal extra items."
      : "PRACTICAL MODE: Rely primarily on the listed ingredients, but suggest 3-6 basic common staples (e.g. olive oil, rice, salt, onions, garlic) as needed for variety."
  }
- Meal Scope: ${mealScope === "full" ? "Include Breakfast, Lunch, and Dinner" : "Include Lunch and Dinner (main meals)"}

PLANNING RULES:
1. SMART PANTRY REUSE: Carry ingredients across days efficiently so fresh produce gets utilized before spoiling.
2. DIVERSE MEALS: Alternate textures and cooking styles (e.g., crisp skillet sauté, rich stew/curry, fresh salad/bowl, baked sheet-pan meal).
3. CHEF PREP TIP: Each day should include 1 actionable efficiency tip (e.g. "Cook double quinoa today to use for tomorrow's lunch").
4. SHOPPING LIST: Provide a consolidated list of missing ingredients / groceries needed for the entire week to execute the plan.

OUTPUT SPECIFICATION:
Return ONLY a valid JSON object matching this structure:
{
  "title": "Creative ${durationDays}-Day Meal Plan Name",
  "summary": "2-3 encouraging sentences summarizing the week's flavors, pantry efficiency, and prep approach.",
  "weeklyShoppingList": ["item 1 with quantity", "item 2 with quantity"],
  "pantryItemsUsed": ["item from user pantry"],
  "days": [
    {
      "dayNumber": 1,
      "dayName": "Day 1 (Monday)",
      "focusTheme": "Quick Skillet & Fresh Greens",
      "chefTip": "Batch chop your aromatics tonight to save 10 minutes tomorrow.",
      "meals": {
        ${mealScope === "full" ? `"breakfast": { "mealType": "Breakfast", "title": "Dish Name", "prepTime": 5, "cookTime": 10, "totalTime": 15, "description": "Short appetizing description", "keyIngredients": ["item 1", "item 2"], "quickInstructions": ["Step 1", "Step 2"] },` : ""}
        "lunch": {
          "mealType": "Lunch",
          "title": "Dish Name",
          "prepTime": 10,
          "cookTime": 15,
          "totalTime": 25,
          "description": "Short appetizing description",
          "keyIngredients": ["item 1", "item 2"],
          "quickInstructions": ["Step 1", "Step 2", "Step 3"]
        },
        "dinner": {
          "mealType": "Dinner",
          "title": "Dish Name",
          "prepTime": 10,
          "cookTime": 20,
          "totalTime": 30,
          "description": "Short appetizing description",
          "keyIngredients": ["item 1", "item 2"],
          "quickInstructions": ["Step 1", "Step 2", "Step 3"]
        }
      }
    }
  ]
}

Make sure "days" contains exactly ${durationDays} days.
Return ONLY raw JSON. No markdown code blocks, backticks, or extra explanation.`;
}

function parseGeminiMealPlanJson(rawText: string, filters: MealPlanFilters): WeeklyMealPlan {
  let cleaned = rawText.trim();
  if (cleaned.startsWith("```json")) {
    cleaned = cleaned.replace(/^```json/, "").replace(/```$/, "").trim();
  } else if (cleaned.startsWith("```")) {
    cleaned = cleaned.replace(/^```/, "").replace(/```$/, "").trim();
  }

  const parsed = JSON.parse(cleaned);

  const days: MealPlanDay[] = (parsed.days || []).map((dayData: any, idx: number) => {
    const dayNumber = Number(dayData.dayNumber) || idx + 1;
    const defaultDayNames = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
    const dayName = dayData.dayName || `Day ${dayNumber} (${defaultDayNames[(dayNumber - 1) % 7]})`;

    const cleanMeal = (meal: any, defaultType: "Breakfast" | "Lunch" | "Dinner") => {
      if (!meal) return undefined;
      const prep = Number(meal.prepTime) || 10;
      const cook = Number(meal.cookTime) || 15;
      return {
        mealType: defaultType,
        title: meal.title || `${defaultType} Idea`,
        prepTime: prep,
        cookTime: cook,
        totalTime: Number(meal.totalTime) || prep + cook,
        description: meal.description || "A delicious home-cooked meal.",
        keyIngredients: Array.isArray(meal.keyIngredients) ? meal.keyIngredients : [],
        quickInstructions: Array.isArray(meal.quickInstructions) ? meal.quickInstructions : [],
      };
    };

    return {
      dayNumber,
      dayName,
      focusTheme: dayData.focusTheme || "Balanced Kitchen Creations",
      chefTip: dayData.chefTip || "Keep prep simple by washing and chopping ingredients ahead.",
      meals: {
        breakfast: dayData.meals?.breakfast
          ? cleanMeal(dayData.meals.breakfast, "Breakfast")
          : undefined,
        lunch: cleanMeal(dayData.meals?.lunch, "Lunch") || {
          mealType: "Lunch",
          title: "Quick Garden Lunch",
          prepTime: 10,
          cookTime: 15,
          totalTime: 25,
          description: "A nourishing midday plate.",
          keyIngredients: filters.ingredients.slice(0, 3),
          quickInstructions: ["Combine ingredients in a skillet.", "Season to taste and serve."],
        },
        dinner: cleanMeal(dayData.meals?.dinner, "Dinner") || {
          mealType: "Dinner",
          title: "Comfort Evening Plate",
          prepTime: 10,
          cookTime: 20,
          totalTime: 30,
          description: "A hearty and satisfying dinner.",
          keyIngredients: filters.ingredients.slice(0, 4),
          quickInstructions: ["Sauté ingredients with seasoning.", "Simmer until tender and enjoy."],
        },
      },
    };
  });

  return {
    id: `plan-${Date.now()}-${Math.random().toString(36).substring(2, 6)}`,
    title: parsed.title || `${filters.durationDays}-Day Chef-Crafted Meal Plan`,
    summary:
      parsed.summary ||
      `A custom ${filters.durationDays}-day culinary roadmap designed around your kitchen staples for minimal waste and maximum flavor.`,
    durationDays: filters.durationDays,
    mealScope: filters.mealScope,
    servings: filters.servings || 1,
    days: days.length > 0 ? days : generateMockMealPlan(filters).days,
    weeklyShoppingList: Array.isArray(parsed.weeklyShoppingList)
      ? parsed.weeklyShoppingList
      : ["Olive oil (if needed)", "Salt & freshly cracked pepper", "Fresh garlic bulb"],
    pantryItemsUsed: Array.isArray(parsed.pantryItemsUsed)
      ? parsed.pantryItemsUsed
      : filters.ingredients,
    createdAt: new Date().toISOString(),
  };
}

export function generateMockMealPlan(filters: MealPlanFilters): WeeklyMealPlan {
  const count = filters.durationDays;
  const dayNames = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"];
  const ings = filters.ingredients.length > 0 ? filters.ingredients : ["Eggs", "Rice", "Tomatoes", "Garlic"];

  const days: MealPlanDay[] = Array.from({ length: count }, (_, i) => {
    const dayNumber = i + 1;
    const baseIng1 = ings[i % ings.length];
    const baseIng2 = ings[(i + 1) % ings.length];

    return {
      dayNumber,
      dayName: `Day ${dayNumber} (${dayNames[i % 7]})`,
      focusTheme: i % 2 === 0 ? "Fast Pan Sizzle & Crunch" : "Comfort Simmer & Velvety Sauces",
      chefTip:
        i === 0
          ? "Prep your aromatics and grains in advance to breeze through the week."
          : `Re-use leftover ingredients from Day ${dayNumber - 1} to speed up today's cooking!`,
      meals: {
        breakfast:
          filters.mealScope === "full"
            ? {
                mealType: "Breakfast",
                title: `Sunshine Scramble with ${baseIng1}`,
                prepTime: 5,
                cookTime: 7,
                totalTime: 12,
                description: `A fluffy, satisfying breakfast featuring pan-seared ${baseIng1} with light seasoning.`,
                keyIngredients: [baseIng1, "Olive oil or butter", "Salt and pepper"],
                quickInstructions: [
                  `Whisk gently and heat a skillet with a drop of oil.`,
                  `Sauté ${baseIng1} lightly until tender.`,
                  `Pour in eggs or fold ingredients together until fluffy.`,
                ],
              }
            : undefined,
        lunch: {
          mealType: "Lunch",
          title: `Warm ${baseIng1} & ${baseIng2} Power Bowl`,
          prepTime: 10,
          cookTime: 15,
          totalTime: 25,
          description: `A vibrant midday fuel bowl highlighting tender ${baseIng1} tossed with ${baseIng2}.`,
          keyIngredients: [baseIng1, baseIng2, "Pantry seasonings"],
          quickInstructions: [
            `Chop ${baseIng1} and ${baseIng2} into bite-sized pieces.`,
            `Sizzle over medium heat for 8 minutes until aromatic.`,
            `Plate warm with your choice of dressing or grains.`,
          ],
        },
        dinner: {
          mealType: "Dinner",
          title: `Rustic Pan-Roasted ${baseIng1} Feast`,
          prepTime: 12,
          cookTime: 20,
          totalTime: 32,
          description: `A comforting dinner with caramelized ${baseIng1}, aromatic spices, and a golden finish.`,
          keyIngredients: [baseIng1, baseIng2, "Herbs & spices"],
          quickInstructions: [
            `Sear ${baseIng1} in a heavy-bottomed skillet until browned at edges.`,
            `Fold in ${baseIng2} and simmer gently for 10 minutes.`,
            `Garnish with fresh herbs and serve piping hot.`,
          ],
        },
      },
    };
  });

  return {
    id: `mock-plan-${Date.now()}`,
    title: `${count}-Day Balanced Kitchen Meal Plan`,
    summary: `A practical ${count}-day rotation built around your ingredients (${ings.join(", ")}), designed for quick cooking, zero food waste, and wholesome variety.`,
    durationDays: count,
    mealScope: filters.mealScope,
    servings: filters.servings || 1,
    days,
    weeklyShoppingList: [
      "Extra virgin olive oil",
      "Sea salt & black pepper",
      "Garlic bulb",
      "Lemon or lime (for freshness)",
      "Fresh herbs (parsley or cilantro)",
    ],
    pantryItemsUsed: ings,
    createdAt: new Date().toISOString(),
  };
}

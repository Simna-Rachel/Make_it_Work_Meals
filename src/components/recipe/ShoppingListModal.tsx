"use client";

import React, { useState, useCallback } from "react";
import { Recipe } from "@/types/recipe";
import {
  X,
  ShoppingCart,
  Copy,
  CheckCircle2,
  CheckCheck,
  Plus,
  Trash2,
  AlertCircle,
  Sparkles,
} from "lucide-react";

interface ShoppingListModalProps {
  recipes: Recipe[];
  isOpen: boolean;
  onClose: () => void;
}

interface ShoppingItem {
  id: string;
  text: string;
  checked: boolean;
  source: "missing" | "custom";
  recipeTitle?: string;
}

function buildInitialItems(recipes: Recipe[]): ShoppingItem[] {
  const seen = new Set<string>();
  const items: ShoppingItem[] = [];

  for (const recipe of recipes) {
    if (!recipe.missingIngredients || recipe.missingIngredients.length === 0) continue;
    for (const ing of recipe.missingIngredients) {
      const key = ing.trim().toLowerCase();
      if (!seen.has(key) && key) {
        seen.add(key);
        items.push({
          id: `${recipe.id}-${key}`,
          text: ing.trim(),
          checked: false,
          source: "missing",
          recipeTitle: recipe.title,
        });
      }
    }
  }

  return items;
}

export function ShoppingListModal({ recipes, isOpen, onClose }: ShoppingListModalProps) {
  const [items, setItems] = useState<ShoppingItem[]>(() => buildInitialItems(recipes));
  const [newItem, setNewItem] = useState("");
  const [copied, setCopied] = useState(false);

  // Rebuild items when recipes change
  React.useEffect(() => {
    setItems(buildInitialItems(recipes));
  }, [recipes]);

  const allMissing = items.filter((i) => i.source === "missing");
  const customItems = items.filter((i) => i.source === "custom");
  const uncheckedCount = items.filter((i) => !i.checked).length;

  const toggleItem = (id: string) => {
    setItems((prev) =>
      prev.map((item) => (item.id === id ? { ...item, checked: !item.checked } : item))
    );
  };

  const removeItem = (id: string) => {
    setItems((prev) => prev.filter((i) => i.id !== id));
  };

  const addCustomItem = () => {
    const text = newItem.trim();
    if (!text) return;
    setItems((prev) => [
      ...prev,
      {
        id: `custom-${Date.now()}`,
        text,
        checked: false,
        source: "custom",
      },
    ]);
    setNewItem("");
  };

  const clearChecked = () => {
    setItems((prev) => prev.filter((i) => !i.checked));
  };

  const copyToClipboard = () => {
    const unchecked = items.filter((i) => !i.checked);
    const text = `Shopping List\n\n${unchecked.map((i) => `• ${i.text}`).join("\n")}\n\n— Generated by Make It Work Meals`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  if (!isOpen) return null;

  const hasItems = items.length > 0;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-5 backdrop-blur-md bg-stone-900/60 animate-in fade-in duration-200">
      <div
        className="relative w-full max-w-lg bg-white rounded-3xl shadow-2xl border border-stone-200 overflow-hidden flex flex-col max-h-[88vh]"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-5 bg-white border-b border-stone-100">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-orange-100 flex items-center justify-center">
              <ShoppingCart className="w-5 h-5 text-orange-600" />
            </div>
            <div>
              <h2 className="text-lg font-black text-stone-900">Shopping List</h2>
              <p className="text-xs text-stone-500">
                {uncheckedCount} item{uncheckedCount !== 1 ? "s" : ""} needed
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-full bg-stone-100 hover:bg-stone-200 text-stone-600 transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-5 space-y-5">
          {/* No missing items info */}
          {!hasItems && (
            <div className="flex flex-col items-center justify-center py-10 text-center">
              <div className="w-16 h-16 rounded-full bg-emerald-100 flex items-center justify-center mb-4">
                <CheckCheck className="w-8 h-8 text-emerald-600" />
              </div>
              <h3 className="font-bold text-stone-900 mb-1">You have everything!</h3>
              <p className="text-sm text-stone-500 max-w-xs">
                None of your generated recipes require extra ingredients you don't already have.
              </p>
              <p className="text-xs text-stone-400 mt-3">
                You can still add custom items below if needed.
              </p>
            </div>
          )}

          {/* Missing ingredients grouped */}
          {allMissing.length > 0 && (
            <div className="space-y-2">
              <div className="flex items-center gap-2">
                <AlertCircle className="w-3.5 h-3.5 text-amber-600" />
                <p className="text-xs font-bold text-amber-700 uppercase tracking-wide">
                  Missing from your kitchen ({allMissing.length})
                </p>
              </div>
              <div className="space-y-2">
                {allMissing.map((item) => (
                  <ShoppingItemRow
                    key={item.id}
                    item={item}
                    onToggle={toggleItem}
                    onRemove={removeItem}
                  />
                ))}
              </div>
            </div>
          )}

          {/* Custom items */}
          {customItems.length > 0 && (
            <div className="space-y-2">
              <div className="flex items-center gap-2">
                <Sparkles className="w-3.5 h-3.5 text-stone-500" />
                <p className="text-xs font-bold text-stone-500 uppercase tracking-wide">
                  Added by you ({customItems.length})
                </p>
              </div>
              <div className="space-y-2">
                {customItems.map((item) => (
                  <ShoppingItemRow
                    key={item.id}
                    item={item}
                    onToggle={toggleItem}
                    onRemove={removeItem}
                  />
                ))}
              </div>
            </div>
          )}

          {/* Add custom item */}
          <div className="space-y-2">
            <p className="text-xs font-bold text-stone-500 uppercase tracking-wide">
              Add your own item
            </p>
            <div className="flex gap-2">
              <input
                type="text"
                value={newItem}
                onChange={(e) => setNewItem(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter") {
                    e.preventDefault();
                    addCustomItem();
                  }
                }}
                placeholder="e.g. 2 cups basmati rice"
                className="flex-1 px-4 py-2.5 rounded-xl border border-stone-200 focus:border-orange-400 focus:ring-4 focus:ring-orange-100 text-stone-800 placeholder-stone-400 text-sm outline-none transition-all"
              />
              <button
                onClick={addCustomItem}
                disabled={!newItem.trim()}
                className="px-4 py-2.5 rounded-xl bg-orange-500 hover:bg-orange-600 text-white font-bold text-sm flex items-center gap-1.5 disabled:opacity-40 transition-colors cursor-pointer"
              >
                <Plus className="w-4 h-4" />
                Add
              </button>
            </div>
          </div>
        </div>

        {/* Footer actions */}
        <div className="px-5 py-4 bg-stone-50 border-t border-stone-100 flex flex-col sm:flex-row items-center gap-2.5">
          {copied && (
            <div className="w-full sm:w-auto px-4 py-2 bg-emerald-50 border border-emerald-200 rounded-full text-emerald-800 text-xs font-semibold flex items-center gap-1.5">
              <CheckCircle2 className="w-3.5 h-3.5" />
              Copied to clipboard!
            </div>
          )}

          <div className="flex items-center gap-2 w-full sm:w-auto sm:ml-auto">
            {items.some((i) => i.checked) && (
              <button
                onClick={clearChecked}
                className="flex items-center gap-1.5 px-3.5 py-2 rounded-full border border-stone-200 text-stone-600 text-xs font-semibold hover:bg-stone-100 transition-colors cursor-pointer"
              >
                <Trash2 className="w-3.5 h-3.5" />
                Clear checked
              </button>
            )}
            <button
              onClick={copyToClipboard}
              disabled={uncheckedCount === 0}
              className="flex items-center gap-1.5 px-4 py-2 rounded-full bg-orange-500 hover:bg-orange-600 text-white text-xs font-bold disabled:opacity-40 transition-colors cursor-pointer"
            >
              <Copy className="w-3.5 h-3.5" />
              Copy List
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}

function ShoppingItemRow({
  item,
  onToggle,
  onRemove,
}: {
  item: ShoppingItem;
  onToggle: (id: string) => void;
  onRemove: (id: string) => void;
}) {
  return (
    <div
      className={`flex items-center gap-3 p-3 rounded-xl border transition-all ${
        item.checked
          ? "bg-stone-50 border-stone-200"
          : "bg-white border-stone-200 hover:border-orange-200 hover:bg-orange-50/20"
      }`}
    >
      <button
        onClick={() => onToggle(item.id)}
        className={`w-5 h-5 rounded-full border-2 flex items-center justify-center flex-shrink-0 transition-all cursor-pointer ${
          item.checked
            ? "bg-emerald-600 border-emerald-600"
            : "border-stone-300 hover:border-orange-400"
        }`}
      >
        {item.checked && <CheckCheck className="w-3 h-3 text-white" />}
      </button>

      <div className="flex-1 min-w-0">
        <span
          className={`text-sm font-medium transition-all ${
            item.checked ? "line-through text-stone-400" : "text-stone-800"
          }`}
        >
          {item.text}
        </span>
        {item.recipeTitle && !item.checked && (
          <p className="text-[10px] text-stone-400 mt-0.5 truncate">
            for {item.recipeTitle}
          </p>
        )}
      </div>

      <button
        onClick={() => onRemove(item.id)}
        className="p-1 rounded-lg text-stone-400 hover:text-rose-500 hover:bg-rose-50 transition-colors cursor-pointer flex-shrink-0"
        title="Remove item"
      >
        <X className="w-3.5 h-3.5" />
      </button>
    </div>
  );
}
